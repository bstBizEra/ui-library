import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const OWN = "bstBizEra/ui-library/";
const USAGE = "usage: node scripts/catalog.mjs [--check] <tag>   e.g. v1.0.0";

const NOT_YET = [
  ["Tabler Icons", "more icons, same 24 px stroke as lucide"],
  ["Simple Icons", "brand logos"],
  ["shadcn Charts", "chart components built on the shadcn chart primitives"],
  ["shadcn AI Elements", "chat and AI interface components"],
  ["assistant-ui", "chat UI for AI assistants"],
  ["coss ui", "accessible component set on Base UI"],
  ["ReUI", "extra shadcn-style components and patterns"],
  ["Magic UI", "animated landing-page components"],
  ["8bitcn", "pixel-art (8-bit) styled components"],
  ["Neobrutalism components", "neobrutalist styled components"],
];

const cell = (s) => String(s ?? "").replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();

// Reads the header comment lines (// Key: value); they sit after the import block, so scan the whole file.
function header(file) {
  const out = {};
  for (const line of fs.readFileSync(file, "utf8").split(/\r?\n/)) {
    const m = line.match(/^\/\/\s*(Source|Upstream|Licence):\s*(.+)$/);
    if (m) out[m[1]] = m[2];
  }
  return out;
}

function describe(item, layerDir) {
  if (!item.files?.length) {
    return { kind: "pointer", source: (item.registryDependencies ?? []).join(", "), licence: "see source" };
  }
  const h = header(path.join(layerDir, item.files[0].path));
  if (h.Source) return { kind: "vendored", source: h.Upstream ?? h.Source, licence: h.Licence ?? "see THIRD_PARTY.md" };
  return { kind: "house", source: "house", licence: "MIT (this repo)" };
}

export function buildCatalog(rootDir, tag) {
  const root = JSON.parse(fs.readFileSync(path.join(rootDir, "registry.json"), "utf8"));
  const out = [
    "# Catalogue",
    "",
    `Generated by \`node scripts/catalog.mjs ${tag}\`. Do not edit by hand. Read this before writing any UI piece: if an item fits, install it instead of writing your own.`,
    "",
    "Items expect shadcn's `@/lib/utils` (`cn`) from `shadcn init`. `lucide-react` is the default icon set; projects already have it through shadcn's `iconLibrary`.",
  ];
  for (const inc of root.include ?? []) {
    const layerDir = path.join(rootDir, path.dirname(inc));
    const items = JSON.parse(fs.readFileSync(path.join(rootDir, inc), "utf8")).items ?? [];
    out.push("", `## ${path.dirname(inc)}`, "", "| Item | Kind | Use when | Install | Source | Licence |", "| --- | --- | --- | --- | --- | --- |");
    for (const item of items) {
      const d = describe(item, layerDir);
      out.push(`| \`${item.name}\` | ${d.kind} | ${cell(item.description)} | \`npx shadcn@latest add ${OWN}${item.name}#${tag}\` | ${cell(d.source)} | ${cell(d.licence)} |`);
    }
  }
  out.push("", "## Not in the library yet", "", "Add these when a project needs them (follow the entry checks in `README.md`):", "");
  for (const [name, use] of NOT_YET) out.push(`- ${name}: ${use}`);
  return out.join("\n") + "\n";
}

export function checkCatalog(rootDir, tag) {
  const file = path.join(rootDir, "CATALOG.md");
  const ok = fs.existsSync(file) && fs.readFileSync(file, "utf8") === buildCatalog(rootDir, tag);
  return { ok, message: ok ? "CATALOG.md is up to date" : `CATALOG.md is out of date: run node scripts/catalog.mjs ${tag}` };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const check = args[0] === "--check";
  const tag = check ? args[1] : args[0];
  if (!tag) {
    console.error(USAGE);
    process.exit(1);
  }
  if (check) {
    const r = checkCatalog(process.cwd(), tag);
    (r.ok ? console.log : console.error)(r.message);
    process.exit(r.ok ? 0 : 1);
  }
  fs.writeFileSync(path.join(process.cwd(), "CATALOG.md"), buildCatalog(process.cwd(), tag));
  console.log("wrote CATALOG.md");
}
